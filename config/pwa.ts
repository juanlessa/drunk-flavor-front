import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { ModuleOptions as PwaModuleOptions } from '@vite-pwa/nuxt';

// Dark theme background, also used as the icon background by `pwa-assets.config.ts`. A manifest
// cannot follow the user's theme, so the installed app opens (splash screen and window frame) in
// the dark palette; the page itself still switches theme through the `theme-color` meta tag.
export const PWA_BACKGROUND_COLOR = '#0B1220';

/** Static page the service worker shows when a navigation fails because the device is offline. */
const OFFLINE_FALLBACK_URL = '/offline.html';

const offlinePageRevision = () =>
	createHash('md5')
		.update(readFileSync(fileURLToPath(new URL('../public/offline.html', import.meta.url))))
		.digest('hex');

export const pwaOptions: PwaModuleOptions = {
	// A new service worker waits until the installed app is reopened instead of reloading the page
	// under the user, which could drop what they were typing in a form.
	registerType: 'prompt',

	manifest: {
		id: '/',
		name: 'DrunkFlavor',
		short_name: 'DrunkFlavor',
		description:
			'Find drinks you can make with the ingredients you have and share your own recipes.',
		lang: 'en',
		// `/` is language-neutral: it redirects to the saved or browser language, so the installed
		// app opens in the right one without a manifest per language.
		start_url: '/',
		scope: '/',
		display: 'standalone',
		orientation: 'portrait',
		background_color: PWA_BACKGROUND_COLOR,
		theme_color: PWA_BACKGROUND_COLOR,
		categories: ['food', 'lifestyle'],
		// Generated by `npm run pwa:assets`. Maskable icons are listed on their own entry: sharing
		// one file between the "any" and "maskable" purposes makes one of the two look wrong.
		icons: [
			{ src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png' },
			{ src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png' },
			{
				src: '/icons/icon-maskable-512.png',
				sizes: '512x512',
				type: 'image/png',
				purpose: 'maskable'
			}
		]
	},

	workbox: {
		// The pages are server-rendered, so there is no app shell to fall back to. Only the build
		// assets and the offline page are precached; API responses are never cached because they
		// depend on who is signed in.
		navigateFallback: null,
		globPatterns: ['**/*.{js,css,png,svg,ico,woff,woff2}'],
		globIgnores: ['images/og-default.png'],
		// Listed by hand because the module rewrites globbed `.html` entries to extensionless URLs
		// (`/offline`), which this static file is not served under. The revision changes with the
		// file so the worker refreshes its copy when the page is edited.
		additionalManifestEntries: [{ url: OFFLINE_FALLBACK_URL, revision: offlinePageRevision() }],
		cleanupOutdatedCaches: true,
		runtimeCaching: [
			{
				urlPattern: ({ request }) => request.mode === 'navigate',
				handler: 'NetworkOnly',
				options: { precacheFallback: { fallbackURL: OFFLINE_FALLBACK_URL } }
			}
		]
	},

	client: { installPrompt: false },
	devOptions: { enabled: false }
};
